const { DataTypes } = require('sequelize');
const connection = require('../database/connection');
const sequelize = connection.sequelize;

const Achievement = sequelize.define('Achievement', {,
id: {,
type: DataTypes.UUID,
defaultValue: DataTypes.UUIDV4,
primaryKey: true },
name: {,
type: DataTypes.STRING(200),
allowNull: false },
description: {,
type: DataTypes.TEXT,
allowNull: false },
category: {,
type: DataTypes.ENUM('engagement', 'content', 'social', 'financial', 'gaming'),
allowNull: false },
tier: {,
type: DataTypes.ENUM('bronze', 'silver', 'gold', 'platinum', 'diamond'),
allowNull: false,
defaultValue: 'bronze' },
icon: {,
type: DataTypes.STRING(100),
allowNull: true },
criteria: {,
type: DataTypes.JSONB,
allowNull: false },
reward: {,
type: DataTypes.JSONB,
allowNull: true },
isActive: {,
type: DataTypes.BOOLEAN,
allowNull: false,
defaultValue: true }
}, {,
tableName: 'achievements',
timestamps: true,
indexes: [{,
fields: ['category'] }, {,
fields: ['tier'] }] });

const UserAchievement = sequelize.define('UserAchievement', {,
id: {,
type: DataTypes.UUID,
defaultValue: DataTypes.UUIDV4,
primaryKey: true },
userId: {,
type: DataTypes.UUID,
allowNull: false },
achievementId: {,
type: DataTypes.UUID,
allowNull: false },
unlockedAt: {,
type: DataTypes.DATE,
allowNull: false,
defaultValue: DataTypes.NOW },
progress: {,
type: DataTypes.JSONB,
allowNull: true,
defaultValue: {} }
}, {,
tableName: 'user_achievements',
timestamps: true,
indexes: [{,
fields: ['userId'] }, {,
fields: ['achievementId'] }] });

module.exports = { Achievement, UserAchievement };
