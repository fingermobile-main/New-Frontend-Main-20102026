import React, {} from 'react';
import PageHeader from '../components/PageHeader';
import useShowcaseData from '../hooks/useShowcaseData';

interface ShowcaseItemProps {
  item: {
    title: string;
    imageUrl: string;
    description?: string;
    prompt: string;
  };
}

const ShowcaseItem: React.FC<ShowcaseItemProps> = ({ item }) => (
  <div className="bg-white rounded-3xl shadow-sm border border-slate-300 overflow-hidden my-6">
    <div className="p-6 border-b border-slate-200">
      <h2 className="text-2xl font-black text-slate-900">{item.title}</h2>
    </div>
    <img src={item.imageUrl} alt={item.title} className="w-full h-auto object-contain bg-slate-100 max-w-full" loading="lazy" />
    <div className="p-6 sm:p-8 space-y-4">
      <div>
        <h3 className="font-bold text-slate-900 text-base mb-1">Description</h3>
        <p className="text-slate-700 font-medium leading-relaxed">{item.description}</p>
      </div>
      <div>
        <h3 className="font-bold text-slate-900 text-base mb-1">Generation Prompt</h3>
        <pre className="bg-slate-950 text-slate-200 text-xs p-4 rounded-2xl overflow-x-auto border border-slate-800 font-mono">
          <code>{item.prompt}</code>
        </pre>
      </div>
    </div>
  </div>
);

const ShowcasePage: React.FC = () => {
  const { showcaseItems, loading, error, refreshData } = useShowcaseData();

  if (loading) {
    return (
      <div className="bg-slate-50 min-h-screen text-center py-12">
        <PageHeader
          title="Application Showcase"
          description="Photorealistic UI mockups generated by AI to guide development."
        />
        <p className="text-slate-700 font-medium mt-4">Loading showcase items...</p>
      </div>
    );
  }

  if (error) {
    return (
      <div className="bg-slate-50 min-h-screen text-center py-12 text-rose-600">
        <PageHeader
          title="Application Showcase"
          description="Photorealistic UI mockups generated by AI to guide development."
        />
        <p className="mt-4 font-bold">Error: {error} <button onClick={refreshData} className="ml-2 px-3 py-1 bg-rose-600 text-white rounded-lg">Retry</button></p>
      </div>
    );
  }

  return (
    <div className="bg-slate-50 min-h-screen">
      <PageHeader
        title="Application Showcase"
        description="Photorealistic UI mockups generated by AI to guide development."
      />
      <div className="w-full max-w-[1536px] 2xl:max-w-[1680px] mx-auto px-4 sm:px-6 lg:px-8 py-8">
        {showcaseItems.map(item => <ShowcaseItem key={item.title} item={item} />)}
      </div>
    </div>
  );
};

export default ShowcasePage;
